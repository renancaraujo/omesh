import 'dart:convert';
import 'dart:typed_data';

import 'package:archive/archive.dart'
    show Deflate, DeflateLevel, Inflate, ZLibDecoderWeb, ZLibEncoderWeb;
import 'package:mesh/mesh.dart';

const _kPrefix = 'OM:';

/// Bit set on the header byte of every v2 and later hash.
const _kEnvelopeFlag = 0x80;

/// Bit set on the header byte of a hash when its body is DEFLATE compressed.
const _kDeflatedFlag = 0x40;

/// The bits of the header byte that hold the spec version.
const _kSpecVersionMask = 0x3F;

/// A function that encodes a mesh gradient into a hash string.
///
/// Useful for sharing mesh gradients between different platforms, appllications
/// and contexts without the need to share the entire mesh data explcitly.
///
/// The hash is a base64 encoded string that contains the compressed binary
/// representation of the mesh gradient. The hash is prefixed with `OM:` to
/// indicate that it is an O'Mesh hash.
///
/// By default the mesh is encoded with [OMeshBinaryFormatCodec.v2], which is
/// lossless. Pass [codec] to choose another format:
/// * [OMeshBinaryFormatCodec.v2Rounded] for shorter hashes of meshes with
///   very precise coordinates, at the cost of rounding them.
/// * [OMeshBinaryFormatCodec.v1] for hashes that can be read by versions of
///   this package prior to the introduction of
///   [OMeshBinaryFormatCodec.v2].
///
/// [getMeshFromHash] reads hashes generated with any of these codecs.
///
/// Throws an [ArgumentError] when:
/// * [codec] is [OMeshBinaryFormatCodec.v1] and [mesh] has more than 15
///   vertices in a dimension.
/// * [codec] is an [OMeshBinaryFormatCodec.v2Rounded] with decimal places
///   outside 0 to 9.
/// * [codec] writes the v2 format and [mesh] has a width or height outside
///   2 to 255, or fewer vertices or colors than its width times its height.
String getHashFromMesh(
  OMeshRect mesh, {
  OMeshBinaryFormatCodec codec = OMeshBinaryFormatCodec.v2,
}) {
  final bytes = codec.encoder.convert(mesh);
  final packed = codec.specVersion == 1 ? _packV1(bytes) : _pack(bytes);
  final hash = base64Url.encode(packed);
  final unpaded = _removePadding(hash);
  final prefixed = '$_kPrefix$unpaded';
  return prefixed;
}

/// A function that decodes a hash string generated by [getHashFromMesh]
/// back into a mesh gradient.
///
/// The hash is a base64 encoded string that contains the compressed binary
/// representation of the mesh gradient. The hash is prefixed with `OM:` to
/// indicate that it is an O'Mesh hash.
///
/// Hashes generated with every [OMeshBinaryFormatCodec] are supported,
/// including the ones generated by previous versions of this package.
///
/// Throws a [FormatException] when the checksum of the hash does not match.
OMeshRect getMeshFromHash(String hash) {
  final unprefixied = hash.substring(_kPrefix.length);
  final paddedHash = _addPadding(unprefixied);
  final packed = base64Url.decode(paddedHash);
  final bytes = _isV1(packed) ? _unpackV1(packed) : _unpack(packed);
  final layers = OMeshBinaryFormatCodec.v2.decoder.convert(bytes);
  return layers;
}

/// The zlib compression level of v1 hashes.
///
/// Passed explicitly, since a different level changes the hash of a mesh.
const _kV1CompressionLevel = 6;

/// The base-2 logarithm of the zlib window size of v1 hashes.
const _kV1WindowBits = 15;

/// v1 hashes are the whole binary format, zlib compressed.
///
/// Uses the pure Dart implementation from `archive`, so that the same mesh
/// yields the same hash on every platform.
///
/// The stream starts with the bytes 78 01, and the DEFLATE data is what the
/// reference zlib writes at level 6 with memLevel 8.
Uint8List _packV1(Uint8List bytes) {
  return const ZLibEncoderWeb().encodeBytes(
    bytes,
    level: _kV1CompressionLevel,
    windowBits: _kV1WindowBits,
  );
}

/// Decompresses a zlib stream from any writer, including the native zlib of
/// previous versions of this package.
///
/// The checksum is verified so that a damaged stream throws a
/// [FormatException] on every platform.
Uint8List _unpackV1(Uint8List packed) {
  return const ZLibDecoderWeb().decodeBytes(packed, verify: true);
}

/// The amount of bytes of the checksum at the end of v2 and later hashes.
const _kChecksumLength = 2;

/// v2 and later hashes have a header byte with the spec version in the
/// lowest 6 bits, [_kDeflatedFlag] in bit 6 and [_kEnvelopeFlag] in the
/// highest bit, followed by the binary format minus its leading spec version
/// byte, raw DEFLATE compressed only when that makes it smaller, and by the
/// big-endian [_crc16] of every byte before it.
///
/// [_kEnvelopeFlag] is how they are told apart from v1 hashes.
Uint8List _pack(Uint8List bytes) {
  final specVersion = bytes[0];
  final body = Uint8List.sublistView(bytes, 1);
  final deflated =
      Deflate(body, level: DeflateLevel.bestCompression).getBytes();
  final useDeflate = deflated.length < body.length;
  final content = useDeflate ? deflated : body;

  final end = content.length + 1;
  final packed = Uint8List(end + _kChecksumLength)
    ..[0] = _kEnvelopeFlag | (useDeflate ? _kDeflatedFlag : 0) | specVersion
    ..setRange(1, end, content);
  final checksum = _crc16(packed, end);
  return packed
    ..[end] = checksum >> 8
    ..[end + 1] = checksum & 0xFF;
}

Uint8List _unpack(Uint8List packed) {
  if (packed.length <= _kChecksumLength) {
    throw const FormatException("O'Mesh hash is too short");
  }
  final end = packed.length - _kChecksumLength;
  if (_crc16(packed, end) != (packed[end] << 8 | packed[end + 1])) {
    throw const FormatException("O'Mesh hash checksum does not match");
  }

  final header = packed[0];
  final content = Uint8List.sublistView(packed, 1, end);
  final body =
      header & _kDeflatedFlag != 0 ? Inflate(content).getBytes() : content;

  return Uint8List(body.length + 1)
    ..[0] = header & _kSpecVersionMask
    ..setRange(1, body.length + 1, body);
}

/// The CRC-16/CCITT-FALSE of the first [length] of [bytes]: polynomial
/// 0x1021, initial value 0xFFFF, most significant bit first, no final XOR.
///
/// It catches every change that fits in 16 bits, such as a mistyped
/// character or two swapped ones.
int _crc16(Uint8List bytes, int length) {
  var crc = 0xFFFF;
  for (var i = 0; i < length; i++) {
    crc ^= bytes[i] << 8;
    for (var bit = 0; bit < 8; bit++) {
      crc = crc & 0x8000 != 0 ? (crc << 1) ^ 0x1021 : crc << 1;
    }
    crc &= 0xFFFF;
  }
  return crc;
}

/// Whether [bytes] are a v1 hash, a zlib stream. The first byte of a zlib
/// stream (RFC 1950) has its highest bit clear.
bool _isV1(Uint8List bytes) {
  return bytes.isNotEmpty && bytes[0] & _kEnvelopeFlag == 0;
}

String _removePadding(String base64String) {
  // Remove trailing '=' characters
  return base64String.replaceAll(RegExp(r'=+$'), '');
}

String _addPadding(String base64String) {
  // Calculate the padding needed to make the length a multiple of 4
  final paddingNeeded = (4 - base64String.length % 4) % 4;
  return base64String + ('=' * paddingNeeded);
}
