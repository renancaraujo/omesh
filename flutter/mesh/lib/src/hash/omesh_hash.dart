import 'dart:convert';
import 'dart:typed_data';

import 'package:archive/archive.dart'
    show Deflate, DeflateLevel, Inflate, ZLibDecoderWeb, ZLibEncoderWeb;
import 'package:mesh/mesh.dart';
import 'package:mesh/src/hash/omesh_codec.dart';

const _kPrefix = 'OM:';

/// Bit set on the header byte of a hash when its body is DEFLATE compressed.
const _kDeflatedFlag = 0x80;

/// A function that encodes a mesh gradient into a hash string.
///
/// Useful for sharing mesh gradients between different platforms, appllications
/// and contexts without the need to share the entire mesh data explcitly.
///
/// The hash is a base64 encoded string that contains the compressed binary
/// representation of the mesh gradient. The hash is prefixed with `OM:` to
/// indicate that it is an O'Mesh hash.
///
/// By default the mesh is encoded with [OMeshBinaryFormatCodec.v2], which is
/// lossless. Pass [codec] to choose another format:
/// * [OMeshBinaryFormatCodec.v2Rounded] for shorter hashes of meshes with
///   very precise coordinates, at the cost of rounding them.
/// * [OMeshBinaryFormatCodec.v1] for hashes that can be read by versions of
///   this package prior to the introduction of
///   [OMeshBinaryFormatCodec.v2].
///
/// [getMeshFromHash] reads hashes generated with any of these codecs.
String getHashFromMesh(
  OMeshRect mesh, {
  OMeshBinaryFormatCodec codec = OMeshBinaryFormatCodec.v2,
}) {
  final bytes = codec.encoder.convert(mesh);
  final packed = codec.specVersion == 1 ? _packV1(bytes) : _pack(bytes);
  final hash = base64Url.encode(packed);
  final unpaded = _removePadding(hash);
  final prefixed = '$_kPrefix$unpaded';
  return prefixed;
}

/// A function that decodes a hash string generated by [getHashFromMesh]
/// back into a mesh gradient.
///
/// The hash is a base64 encoded string that contains the compressed binary
/// representation of the mesh gradient. The hash is prefixed with `OM:` to
/// indicate that it is an O'Mesh hash.
///
/// Hashes generated with every [OMeshBinaryFormatCodec] are supported,
/// including the ones generated by previous versions of this package.
OMeshRect getMeshFromHash(String hash) {
  final unprefixied = hash.substring(_kPrefix.length);
  final paddedHash = _addPadding(unprefixied);
  final packed = base64Url.decode(paddedHash);
  final bytes = _isZlibStream(packed) ? _unpackV1(packed) : _unpack(packed);
  final layers = OMeshBinaryFormatCodec.v2.decoder.convert(bytes);
  return layers;
}

/// v1 hashes are the whole binary format, zlib compressed.
///
/// Compression always uses the pure Dart implementation from `archive`, even
/// where `dart:io` is available, so that the same mesh yields the same hash
/// on every platform. The native zlib bundled with the Dart VM is optimized
/// differently than the reference algorithm, so its output cannot be
/// reproduced on the web, and may vary across CPUs and SDK versions.
Uint8List _packV1(Uint8List bytes) {
  return const ZLibEncoderWeb().encodeBytes(bytes);
}

/// Accepts any valid zlib stream, including the ones written by the native
/// zlib of previous versions of this package.
///
/// The checksum is verified so that corrupted hashes throw a
/// [FormatException] on every platform.
Uint8List _unpackV1(Uint8List packed) {
  return const ZLibDecoderWeb().decodeBytes(packed, verify: true);
}

/// v2 and later hashes have a header byte with the spec version in the
/// lowest 7 bits and [_kDeflatedFlag] in the highest bit, followed by the
/// binary format minus its leading spec version byte, raw DEFLATE compressed
/// only when that makes it smaller.
///
/// The header byte never looks like the start of a zlib stream, which is how
/// v1 hashes are told apart.
Uint8List _pack(Uint8List bytes) {
  final specVersion = bytes[0];
  final body = Uint8List.sublistView(bytes, 1);
  final deflated =
      Deflate(body, level: DeflateLevel.bestCompression).getBytes();
  final useDeflate = deflated.length < body.length;
  final content = useDeflate ? deflated : body;

  return Uint8List(content.length + 1)
    ..[0] = specVersion | (useDeflate ? _kDeflatedFlag : 0)
    ..setRange(1, content.length + 1, content);
}

Uint8List _unpack(Uint8List packed) {
  if (packed.isEmpty) {
    throw const FormatException("Empty O'Mesh hash");
  }
  final header = packed[0];
  final content = Uint8List.sublistView(packed, 1);
  final body =
      header & _kDeflatedFlag != 0 ? Inflate(content).getBytes() : content;

  return Uint8List(body.length + 1)
    ..[0] = header & 0x7F
    ..setRange(1, body.length + 1, body);
}

/// Whether [bytes] start with a zlib header (RFC 1950): compression method 8
/// and a header checksum that is a multiple of 31.
bool _isZlibStream(Uint8List bytes) {
  return bytes.length >= 2 &&
      bytes[0] & 0x0F == 8 &&
      (bytes[0] * 256 + bytes[1]) % 31 == 0;
}

String _removePadding(String base64String) {
  // Remove trailing '=' characters
  return base64String.replaceAll(RegExp(r'=+$'), '');
}

String _addPadding(String base64String) {
  // Calculate the padding needed to make the length a multiple of 4
  final paddingNeeded = (4 - base64String.length % 4) % 4;
  return base64String + ('=' * paddingNeeded);
}
